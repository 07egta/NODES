//! Bounded 3D power cells by convex half-space clipping.
//! Floating-point construction in normalized coordinates, not exact Delaunay.
//! Errors (including budget exhaustion) never return a partial diagram.
use crate::engine::cancelled;
use crate::mesh_tools::{P, Stop, add, cross, dot, len, mul, sub, unit};
use crate::model::{MAX_TRIANGLES, MAX_VERTICES, Mesh};

const EPS: f64 = 1e-10;
const MAX_SITES: usize = 10_000;
const MAX_WORK: usize = 150_000_000;

#[derive(Clone, Copy, Debug)]
pub struct Site {
    pub point: P,
    /// Squared model units. Zero yields ordinary Voronoi.
    pub weight: f64,
}

#[derive(Clone, Copy, Debug)]
pub struct Bounds {
    pub min: P,
    pub max: P,
}

#[derive(Debug)]
pub struct Cell {
    /// Index in the original site list.
    pub site: usize,
    pub mesh: Mesh,
    pub volume: f64,
    pub centroid: P,
    /// Site indices of faces generated by bisector clipping.
    pub neighbors: Vec<usize>,
}

struct Face {
    polygon: Vec<P>,
    neighbor: Option<usize>,
}

fn budget(work: &mut usize, amount: usize, stop: Stop) -> Result<(), String> {
    *work = work.saturating_add(amount);
    if *work > MAX_WORK {
        return Err("3D Voronoi: work budget exceeded; no partial diagram".into());
    }
    cancelled(stop)
}

fn box_faces(h: P) -> Vec<Face> {
    let [x, y, z] = h;
    let points = [
        [-x, -y, -z],
        [x, -y, -z],
        [x, y, -z],
        [-x, y, -z],
        [-x, -y, z],
        [x, -y, z],
        [x, y, z],
        [-x, y, z],
    ];
    [
        [0, 3, 2, 1],
        [4, 5, 6, 7],
        [0, 1, 5, 4],
        [1, 2, 6, 5],
        [2, 3, 7, 6],
        [3, 0, 4, 7],
    ]
    .into_iter()
    .map(|ids| Face {
        polygon: ids.map(|i| points[i]).to_vec(),
        neighbor: None,
    })
    .collect()
}

fn push_unique(points: &mut Vec<P>, p: P) {
    if !points.iter().any(|&q| len(sub(p, q)) <= EPS) {
        points.push(p);
    }
}

fn mean(points: &[P]) -> P {
    mul(
        points.iter().copied().fold([0.; 3], add),
        1. / points.len() as f64,
    )
}

/// Keep n dot x <= d. n must be unit length.
fn clip(faces: &mut Vec<Face>, n: P, d: f64, neighbor: usize) -> Result<(), String> {
    let (mut lo, mut hi) = (f64::INFINITY, f64::NEG_INFINITY);
    for f in faces.iter() {
        for &p in &f.polygon {
            let s = dot(n, p) - d;
            lo = lo.min(s);
            hi = hi.max(s);
        }
    }
    if hi <= EPS {
        return Ok(());
    }
    if lo >= -EPS {
        faces.clear();
        return Ok(());
    }
    let mut cap = Vec::new();
    let mut result = Vec::new();
    for face in faces.drain(..) {
        let mut out = Vec::new();
        let poly = &face.polygon;
        for k in 0..poly.len() {
            let a = poly[k];
            let b = poly[(k + 1) % poly.len()];
            let da = dot(n, a) - d;
            let db = dot(n, b) - d;
            if da <= 0. {
                push_unique(&mut out, a);
                if da.abs() <= EPS {
                    push_unique(&mut cap, a);
                }
            }
            if (da < 0. && db > 0.) || (da > 0. && db < 0.) {
                let p = add(a, mul(sub(b, a), da / (da - db)));
                push_unique(&mut out, p);
                push_unique(&mut cap, p);
            }
        }
        if out.len() >= 3 {
            result.push(Face {
                polygon: out,
                neighbor: face.neighbor,
            });
        }
    }
    if cap.len() < 3 {
        return Err("3D Voronoi: unstable clipping cap".into());
    }
    let center = mean(&cap);
    let axis = if n[0].abs() < 0.8 {
        [1., 0., 0.]
    } else {
        [0., 1., 0.]
    };
    let u = unit(cross(n, axis)).ok_or("3D Voronoi: invalid clipping normal")?;
    let v = cross(n, u);
    let angle = |p: P| {
        let q = sub(p, center);
        dot(q, v).atan2(dot(q, u))
    };
    cap.sort_by(|&a, &b| angle(a).total_cmp(&angle(b)));
    result.push(Face {
        polygon: cap,
        neighbor: Some(neighbor),
    });
    *faces = result;
    Ok(())
}

fn vertex(vertices: &mut Vec<P>, p: P) -> u32 {
    if let Some(i) = vertices.iter().position(|&q| len(sub(p, q)) <= EPS) {
        i as u32
    } else {
        let i = vertices.len() as u32;
        vertices.push(p);
        i
    }
}

fn make_cell(
    site: usize,
    faces: &[Face],
    origin: P,
    scale: f64,
    stop: Stop,
) -> Result<Cell, String> {
    let mut vertices = Vec::new();
    let mut triangles = Vec::new();
    let mut neighbors = Vec::new();
    for face in faces {
        cancelled(stop)?;
        let ids: Vec<_> = face
            .polygon
            .iter()
            .map(|&p| vertex(&mut vertices, p))
            .collect();
        // Face-center fan keeps collinear boundary vertices shared by adjoining faces.
        let c = vertex(&mut vertices, mean(&face.polygon));
        for k in 0..ids.len() {
            triangles.push([c, ids[k], ids[(k + 1) % ids.len()]]);
        }
        if let Some(n) = face.neighbor {
            neighbors.push(n);
        }
    }
    if vertices.len() > MAX_VERTICES || triangles.len() > MAX_TRIANGLES {
        return Err("3D Voronoi: cell size limit".into());
    }
    let center = mean(&vertices);
    let mut volume = 0.;
    let mut moment = [0.; 3];
    for t in &triangles {
        let [a, b, c] = t.map(|i| sub(vertices[i as usize], center));
        let w = dot(a, cross(b, c)) / 6.;
        if w <= 0. || !w.is_finite() {
            return Err("3D Voronoi: degenerate or reversed face".into());
        }
        volume += w;
        moment = add(moment, mul(add(add(a, b), c), w / 4.));
    }
    let centroid = add(origin, mul(add(center, mul(moment, 1. / volume)), scale));
    let volume = volume * scale.powi(3);
    if !volume.is_finite() || volume <= 0. || !centroid.iter().all(|x| x.is_finite()) {
        return Err("3D Voronoi: invalid physical volume or centroid".into());
    }
    let mesh = Mesh {
        vertices: vertices
            .into_iter()
            .map(|p| add(origin, mul(p, scale)))
            .collect(),
        triangles,
    };
    let audit = crate::mesh_fabrication::audit(&mesh, stop)?;
    if !audit.closed_oriented() || audit.duplicate_vertices != 0 || audit.isolated_vertices != 0 {
        return Err("3D Voronoi: cell failed closed-mesh audit".into());
    }
    neighbors.sort_unstable();
    neighbors.dedup();
    Ok(Cell {
        site,
        mesh,
        volume,
        centroid,
        neighbors,
    })
}

/// Compute cells inside an axis-aligned design box. Weighted sites may have empty
/// cells; such sites are omitted. Near-duplicate sites and numerically thin
/// cells are rejected rather than silently merged. O(n^2) candidate search.
pub fn bounded_power_cells(
    sites: &[Site],
    bounds: Bounds,
    stop: Stop,
) -> Result<Vec<Cell>, String> {
    cancelled(stop)?;
    if sites.is_empty() || sites.len() > MAX_SITES {
        return Err("3D Voronoi: expected 1..=10000 sites".into());
    }
    let extent = sub(bounds.max, bounds.min);
    if !extent.iter().all(|&x| x.is_finite() && x > 0.)
        || !bounds.min.iter().chain(&bounds.max).all(|x| x.abs() <= 1e9)
    {
        return Err("3D Voronoi: invalid bounds".into());
    }
    let scale = extent.into_iter().fold(0., f64::max);
    let origin = add(bounds.min, mul(extent, 0.5));
    let half = mul(extent, 0.5 / scale);
    if half.iter().any(|&x| x <= EPS) {
        return Err("3D Voronoi: near-degenerate bounds".into());
    }
    let mut normalized = Vec::with_capacity(sites.len());
    for s in sites {
        if !s.weight.is_finite()
            || (0..3).any(|k| {
                !s.point[k].is_finite()
                    || s.point[k] < bounds.min[k]
                    || s.point[k] > bounds.max[k]
            })
        {
            return Err("3D Voronoi: invalid or out-of-bounds site".into());
        }
        let weight = s.weight / scale / scale;
        if !weight.is_finite() || weight.abs() > 1e6 {
            return Err("3D Voronoi: weight outside numerical range".into());
        }
        normalized.push(Site {
            point: mul(sub(s.point, origin), 1. / scale),
            weight,
        });
    }
    let mut work = 0usize;
    let mut cells = Vec::new();
    let (mut nv, mut nt) = (0usize, 0usize);
    for (i, p) in normalized.iter().enumerate() {
        let mut faces = box_faces(half);
        let mut radius = len(half) + len(p.point);
        for (j, q) in normalized.iter().enumerate() {
            if j == i {
                continue;
            }
            work += 1;
            if work.is_multiple_of(1024) {
                budget(&mut work, 0, stop)?;
            }
            let delta = sub(q.point, p.point);
            let length = len(delta);
            if length <= EPS {
                return Err("3D Voronoi: duplicate or near-duplicate site".into());
            }
            if faces.is_empty() {
                continue;
            }
            let normal = mul(delta, 1. / length);
            let relative = (length * length + p.weight - q.weight) / (2. * length);
            if relative > radius + EPS {
                continue;
            }
            let cost = faces.iter().map(|f| f.polygon.len()).sum();
            budget(&mut work, cost, stop)?;
            clip(&mut faces, normal, dot(normal, p.point) + relative, j)?;
            radius = faces
                .iter()
                .flat_map(|f| &f.polygon)
                .map(|&v| len(sub(v, p.point)))
                .fold(0., f64::max);
        }
        if !faces.is_empty() {
            let c = make_cell(i, &faces, origin, scale, stop)?;
            nv += c.mesh.vertices.len();
            nt += c.mesh.triangles.len();
            if nv > MAX_VERTICES || nt > MAX_TRIANGLES {
                return Err("3D Voronoi: total mesh size limit".into());
            }
            cells.push(c);
        }
    }
    let expected: f64 = extent.into_iter().product();
    let actual: f64 = cells.iter().map(|c| c.volume).sum();
    if !actual.is_finite() || !expected.is_finite() || (actual - expected).abs() > 1e-7 * expected {
        return Err("3D Voronoi: volume partition validation failed".into());
    }
    Ok(cells)
}

/// One unweighted Lloyd iteration using volume centroids.
pub fn lloyd_step(points: &[P], bounds: Bounds, stop: Stop) -> Result<Vec<P>, String> {
    let sites: Vec<_> = points
        .iter()
        .map(|&point| Site { point, weight: 0. })
        .collect();
    let cells = bounded_power_cells(&sites, bounds, stop)?;
    if cells.len() != points.len() {
        return Err("3D Voronoi: empty cell in Lloyd iteration".into());
    }
    Ok(cells.into_iter().map(|c| c.centroid).collect())
}

#[cfg(test)]
mod tests {
    use super::*;

    const GO: Stop<'static> = &|| false;
    const BOX: Bounds = Bounds {
        min: [0.; 3],
        max: [10.; 3],
    };

    fn site(x: f64, weight: f64) -> Site {
        Site {
            point: [x, 5., 5.],
            weight,
        }
    }

    #[test]
    fn two_cells_and_lloyd() {
        let cells = bounded_power_cells(&[site(2., 0.), site(8., 0.)], BOX, GO).unwrap();
        assert_eq!(cells.len(), 2);
        for (i, cell) in cells.iter().enumerate() {
            assert!((cell.volume - 500.).abs() < 1e-7);
            assert_eq!(cell.neighbors, vec![1 - i]);
            assert!((cell.centroid[0] - (2.5 + 5. * i as f64)).abs() < 1e-8);
        }
        let points = lloyd_step(&[[2., 5., 5.], [8., 5., 5.]], BOX, GO).unwrap();
        assert!((points[0][0] - 2.5).abs() < 1e-8);
    }

    #[test]
    fn power_weights_and_empty_cell() {
        let cells = bounded_power_cells(&[site(2., 12.), site(8., 0.)], BOX, GO).unwrap();
        assert!((cells[0].volume - 600.).abs() < 1e-7);
        let cells = bounded_power_cells(&[site(2., 1000.), site(8., 0.)], BOX, GO).unwrap();
        assert_eq!(cells.len(), 1);
        assert_eq!(cells[0].site, 0);
        assert!((cells[0].volume - 1000.).abs() < 1e-7);
    }

    #[test]
    fn duplicates_and_cancel_are_errors() {
        assert!(bounded_power_cells(&[site(2., 0.), site(2., 1.)], BOX, GO).is_err());
        assert!(bounded_power_cells(&[site(2., 0.)], BOX, &|| true).is_err());
    }

    #[test]
    fn eight_cospherical_grid_sites_partition_box() {
        let mut sites = Vec::new();
        for x in [2.5, 7.5] {
            for y in [2.5, 7.5] {
                for z in [2.5, 7.5] {
                    sites.push(Site {
                        point: [x, y, z],
                        weight: 0.,
                    });
                }
            }
        }
        let cells = bounded_power_cells(&sites, BOX, GO).unwrap();
        assert_eq!(cells.len(), 8);
        for c in cells {
            assert!((c.volume - 125.).abs() < 1e-7);
            assert_eq!(c.neighbors.len(), 3);
        }
    }
}
